export function getStaticBlogBySlug(slug) {
    const normalized = String(slug || "").replace(/^-+|-+$/g, "");
    return (
        STATIC_BLOG_POSTS.find(
            (post) => post.slug === slug || post.slug === normalized
        ) || null
    );
}

