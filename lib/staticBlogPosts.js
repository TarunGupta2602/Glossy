export function getStaticBlogBySlug(slug) {
    const normalized = String(slug || "").replace(/^-+|-+$/g, "");
    return (
        STATIC_BLOG_POSTS.find(
            (post) => post.slug === slug || post.slug === normalized
        ) || null
    );
}

export function listStaticBlogSummaries() {
    return STATIC_BLOG_POSTS.map((post) => ({
        id: post.id,
        title: post.title,
        slug: post.slug,
        description: post.description,
        image: post.image,
        author: post.author,
        date_posted: post.date_posted,
    }));
}
